//ตรวจสิทธิ์ ตามลำดับ ไอดี พาส โรล สถานะ อายุ
function login(inputUser, inputPass, role, isActive, age) {
//ตั้งค่ารหัสผ่านถ้าไม่ตรงจะเข้าไม่ได้
  if (inputUser !== "admin" || inputPass !== "ce385pass") 
    {return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง";}
  

//เช็คว่าบัญชีโดนระงับมั้ย
  if (isActive === false) 
    {return "บัญชีนี้ถูกระงับการใช้งาน";}
  
//ถ้าน้อยกว่า 18 จะเข้าไม่ได้
  if (age < 18) 
    {return "อายุไม่ถึง";}
  
//บทบาทถ้าระบุได้ว่าเป็นใครจะได้สิทธิ์นั้น
  if (role === "อาจารย์") 
   {return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)";}
   else if (role === "นักศึกษา") 
    {return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)";}
  
}
//ทดสอบอย่างน้อย 6 กรณี — สำเร็จ (อาจารย์) · สำเร็จ (นักศึกษา) · รหัสผ่านผิด · ชื่อผู้ใช้ผิด · บัญชีถูกระงับ · อายุไม่ถึง
console.log("1. สำเร็จ (อาจารย์)  ->", login("admin", "ce385pass", "อาจารย์", true, 20));
console.log("2. สำเร็จ (นักศึกษา)  ->", login("admin", "ce385pass", "นักศึกษา", true, 18));
console.log("3. รหัสผ่านผิด        ->", login("admin", "มั่ว", "นักศึกษา", true, 18));
console.log("4. ชื่อผู้ใช้ผิด         ->", login("มั่ว", "ce385pass", "นักศึกษา", true, 18));
console.log("5. บัญชีถูกระงับ       ->", login("admin", "ce385pass", "นักศึกษา", false, 18));
console.log("6. อายุไม่ถึง         ->", login("admin", "ce385pass", "นักศึกษา", true, 16));

//ทำไมต้องตรวจ username/password ก่อน ตรวจ role
//เพราะว่าต้องรู้ว่าเป็นใครก่อนถ้าไปเช็คโรลก่อนเราจะไม่รู้ว่าเป็นใครไม่งั้นคนอื่นอาจจะเดาการทำงานได้

//ถ้าย้ายการตรวจ "อายุไม่ถึงเกณฑ์" ขึ้นไปเป็นข้อแรก จะเกิดปัญหาอะไร (คิดในแง่ความปลอดภัย: เราจะบอกอะไรกับคนที่ยังไม่ได้พิสูจน์ตัวตน)
//อาจจะโดนเจาะได้เพราะคนเจาะระบบจะรู้ได้เลยว่าคนนี้ไม่ถึงอายุไม่ถึงเกณฑ์โดยที่ไม่ต้องมีรหัสจะเข้าข่ายข้อมูลรัวไหลได้